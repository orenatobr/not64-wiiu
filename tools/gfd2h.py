#!/usr/bin/env python3
"""
Convert GFD (.gsh) files produced by decaf's latte-assembler into a C++ header in the
format of the dborth drivers' shaders (program word array + register word array).

  gfd2h.py <out.h> <name>=<file.gsh> ...

For every gsh the first vertex shader and first pixel shader are extracted. For
a shader name NAME the header defines
  static const uint32_t kNAME_VsProgram[] / kNAME_VsRegs[]   (only if the file has a VS)
  static const uint32_t kNAME_PsProgram[] / kNAME_PsRegs[]
Words are the big-endian values as the Wii U CPU sees them, exactly what
GX2VertexShader::program / ::regs and GX2PixelShader expect.
"""
import struct
import sys

VS_REGS_BYTES = 0xD0
PS_REGS_BYTES = 0xA4
BLK_VS_HEADER, BLK_VS_PROGRAM, BLK_PS_HEADER, BLK_PS_PROGRAM = 3, 5, 6, 7


def parse_gfd(path):
    data = open(path, 'rb').read()
    magic, hsize = struct.unpack('>II', data[:8])
    if magic != 0x47667832:
        raise SystemExit('%s: not a GFD file' % path)
    pos = hsize
    blocks = {}
    while pos + 0x20 <= len(data):
        bmagic, bhs, _, _, btype, bsize, _, _ = struct.unpack('>8I', data[pos:pos + 0x20])
        if bmagic != 0x424C4B7B:
            raise SystemExit('%s: bad block magic at %#x' % (path, pos))
        body = data[pos + bhs:pos + bhs + bsize]
        if btype == 1:
            break
        blocks.setdefault(btype, body)
        pos += bhs + bsize
    return blocks


def words(b):
    if len(b) % 4:
        b = b + b'\0' * (4 - len(b) % 4)
    return struct.unpack('>%dI' % (len(b) // 4), b)


def fmt(name, ws):
    lines = ['static const uint32_t %s[%d] = {' % (name, len(ws))]
    for i in range(0, len(ws), 4):
        lines.append('\t' + ','.join('0x%08x' % w for w in ws[i:i + 4]) + (',' if i + 4 < len(ws) else ''))
    lines.append('};')
    return '\n'.join(lines)


def main(argv):
    out = argv[1]
    parts = ['/* Generated by tools/gfd2h.py from the Latte assembly in wiiu/source/gx2gx/shaders/asm.',
             ' * Do not edit; run tools/build-shaders.sh. */',
             '#ifndef GX2GX_SHADER_DATA_H', '#define GX2GX_SHADER_DATA_H', '', '#include <stdint.h>', '']
    seen_vs = False
    for spec in argv[2:]:
        name, path = spec.split('=', 1)
        blk = parse_gfd(path)
        if BLK_VS_HEADER in blk and not seen_vs:
            seen_vs = True
            regs = words(blk[BLK_VS_HEADER][:VS_REGS_BYTES])
            parts.append(fmt('k%s_VsProgram' % name, words(blk[BLK_VS_PROGRAM])))
            parts.append(fmt('k%s_VsRegs' % name, regs))
        if BLK_PS_HEADER in blk:
            regs = words(blk[BLK_PS_HEADER][:PS_REGS_BYTES])
            parts.append(fmt('k%s_PsProgram' % name, words(blk[BLK_PS_PROGRAM])))
            parts.append(fmt('k%s_PsRegs' % name, regs))
    parts.append('')
    parts.append('#endif')
    open(out, 'w').write('\n'.join(parts) + '\n')


if __name__ == '__main__':
    main(sys.argv)
