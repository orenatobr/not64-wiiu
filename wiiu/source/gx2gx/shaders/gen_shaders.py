# --------------------------------------------------------------------------
# emission
# --------------------------------------------------------------------------


def fmt_group(counter, grp):
    lines = []
    for k, (slot, name, dst, srcs, props) in enumerate(grp):
        text = '%s: %s %s' % (slot, name, dst)
        if srcs:
            text += ', ' + ', '.join(('PS%d' % (counter - 1)) if x == 'PS' else x for x in srcs)
        if props:
            text += ' ' + props
        lines.append(('%d ' % counter if k == 0 else '  ') + text)
    return '\n'.join(lines)


def emit(items, header, prologue_cf, epilogue_cf):
    cf = []
    n = 0
    body = []
    pc = 0   # running ALU group / TEX instruction counter (assembler requirement)
    for pre in prologue_cf:
        body.append('%02d %s' % (n, pre)); n += 1
    for kind, data in items:
        if kind == 'tex':
            body.append('%02d TEX:' % n); n += 1
            for k, t in enumerate(data):
                body.append('%d %s %s, %s, %s, %s' % (pc, t[0], t[1], t[2], t[3], t[4])); pc += 1
        else:
            for clause in split_alu(data):
                body.append('%02d ALU:' % n); n += 1
                for grp in clause:
                    body.append(fmt_group(pc, grp)); pc += 1
    for ex in epilogue_cf:
        body.append('%02d %s' % (n, ex)); n += 1
    body.append('END_OF_PROGRAM')
    return header + '\n' + '\n'.join(body) + '\n'


def gen(outdir):
    import os
    os.makedirs(outdir, exist_ok=True)
    vs = emit([('alu', build_vs())], VS_HEADER, ['CALL_FS NO_BARRIER'],
              ['EXP_DONE: POS0, R5.xyzw', 'EXP: PARAM0, R2.xyzw NO_BARRIER',
               'EXP: PARAM1, R6.xyzw NO_BARRIER', 'EXP_DONE: PARAM2, R7.xyzw NO_BARRIER'])
    open(os.path.join(outdir, 'vs_gx.asm'), 'w').write(vs)
    for n in range(1, MAX_STAGES + 1):
        ps = emit(build_ps(n), PS_HEADER % (n, n), [], ['EXP_DONE: PIX0, R3.xyzw'])
        open(os.path.join(outdir, 'ps_tev%d.asm' % n), 'w').write(ps)


# --------------------------------------------------------------------------
# static lint of the groups (conservative subset of the Latte ALU rules)
# --------------------------------------------------------------------------
OPERAND = re.compile(r'^(-?)(R(\d+)|C(\d+)|PS|PV|([0-9.]+)f)(?:\.([xyzw]))?$')


def parse_operand(txt):
    m = OPERAND.match(txt)
    if not m:
        raise ValueError('bad operand ' + txt)
    neg = m.group(1) == '-'
    if m.group(3) is not None:
        return ('R', int(m.group(3)), m.group(6), neg)
    if m.group(4) is not None:
        return ('C', int(m.group(4)), m.group(6), neg)
    if m.group(2) in ('PS', 'PV'):
        return (m.group(2), 0, None, neg)
    return ('L', float(m.group(5)), None, neg)


def lint_group(grp, where):
    errs = []
    slots = [op[0] for op in grp]
    if len(set(slots)) != len(slots):
        errs.append('%s: duplicate slot %s' % (where, slots))
    dsts = [op[2] for op in grp if op[2] != '____']
    if len(set(dsts)) != len(dsts):
        errs.append('%s: duplicate destination %s' % (where, dsts))
    for op in grp:
        d = op[2]
        if d != '____':
            dm = re.match(r'R(\d+)\.([xyzw])$', d)
            if not dm:
                errs.append('%s: bad destination %s' % (where, d))
            elif op[0] != 't' and dm.group(2) != op[0]:
                errs.append('%s: dst channel %s must match slot %s' % (where, d, op[0]))
    consts = set()
    const_pos = set()
    for op in grp:
        pos = []
        for k, s in enumerate(op[3]):
            p = parse_operand(s)
            if p[0] == 'C':
                consts.add(p[1])
                pos.append(k)
            if p[0] == 'R' and p[2] is None:
                errs.append('%s: GPR operand without channel %s' % (where, s))
        const_pos.add(tuple(pos))
        if op[1] == 'MULADD' and op[0] == 't':
            errs.append('%s: op3 in t slot' % where)
        if op[1] == 'MULADD' and len(op[3]) != 3:
            errs.append('%s: MULADD needs 3 sources' % where)
    if len(consts) > 1:
        errs.append('%s: more than one constant register in a group: %s' % (where, sorted(consts)))
    if len(const_pos) > 1:
        errs.append('%s: constant operand position differs across lanes' % where)
    if len(grp) > 5:
        errs.append('%s: more than 5 slots' % where)
    return errs


def lint():
    errs = []
    for name, groups in [('vs', build_vs())] + [('ps%d' % n, [x for it in build_ps(n) if it[0] == 'alu' for x in it[1]])
                                              for n in range(1, MAX_STAGES + 1)]:
        for k, grp in enumerate(groups):
            errs += lint_group(grp, '%s#%d' % (name, k))
    # PS consumers must directly follow the group that produced PS
    for n in range(1, MAX_STAGES + 1):
        groups = [x for it in build_ps(n) if it[0] == 'alu' for x in it[1]]
        for k, grp in enumerate(groups):
            if any('PS' in op[3] for op in grp):
                if k == 0 or not any(op[0] == 't' for op in groups[k - 1]):
                    errs.append('ps%d#%d: PS read without a t-slot producer in the previous group' % (n, k))
    return errs


# --------------------------------------------------------------------------
# simulator (idealised Latte ALU semantics: all sources read before any write of a group)
# --------------------------------------------------------------------------


def f32(x):
    return struct.unpack('f', struct.pack('f', x))[0]


def run_groups(groups, gpr, consts, ps_reg=[0.0]):
    ps = 0.0
    for grp in groups:
        writes = []
        new_ps = ps
        for slot, name, dst, srcs, props in grp:
            vals = []
            for s in srcs:
                kind, idx, ch, neg = parse_operand(s)
                if kind == 'R':
                    v = gpr[idx][SLOT_CHAN[ch]]
                elif kind == 'C':
                    v = consts[idx * 4 + SLOT_CHAN[ch]]
                elif kind == 'PS':
                    v = ps
                else:
                    v = idx
                vals.append(-v if neg else v)
            if name == 'MOV':
                r = vals[0]
            elif name == 'ADD':
                r = vals[0] + vals[1]
            elif name == 'MUL':
                r = 0.0 if (vals[0] == 0.0 or vals[1] == 0.0) else vals[0] * vals[1]
            elif name == 'MULADD':
                p = 0.0 if (vals[0] == 0.0 or vals[1] == 0.0) else vals[0] * vals[1]
                r = p + vals[2]
            elif name == 'MAX':
                r = max(vals[0], vals[1])
            elif name == 'MIN':
                r = min(vals[0], vals[1])
            elif name == 'RECIP_IEEE':
                r = (1.0 / vals[0]) if vals[0] != 0.0 else float('inf')
            else:
                raise ValueError('sim: unsupported op ' + name)
            if 'CLAMP' in props:
                r = min(max(r, 0.0), 1.0)
            r = f32(r)
            if slot == 't':
                new_ps = r
            if dst != '____':
                m = re.match(r'R(\d+)\.([xyzw])$', dst)
                writes.append((int(m.group(1)), SLOT_CHAN[m.group(2)], r))
        for reg, c, v in writes:
            gpr[reg][c] = v
        ps = new_ps


def simulate_ps(nstages, consts, ras, tex0, tex1, z=0.0, w=1.0):
    gpr = [[0.0] * 4 for _ in range(16)]
    gpr[0] = list(ras)
    gpr[2] = [z, w, 0.0, 0.0]
    for it in build_ps(nstages):
        if it[0] == 'tex':
            gpr[7] = list(tex0)
            gpr[8] = list(tex1)
        else:
            run_groups(it[1], gpr, consts)
    return gpr[3]


def sim_check(path):
    vec = open(path).read().split('\n')
    bad = 0
    cases = 0
    k = 0
    while k < len(vec):
        if not vec[k].startswith('case'):
            k += 1
            continue
        n = int(vec[k].split()[1])
        consts = [float(x) for x in vec[k + 1].split()]
        ras = [float(x) for x in vec[k + 2].split()]
        t0 = [float(x) for x in vec[k + 3].split()]
        t1 = [float(x) for x in vec[k + 4].split()]
        exp = [float(x) for x in vec[k + 5].split()]
        got = simulate_ps(n, consts, ras, t0, t1)
        cases += 1
        if any(abs(a - b) > 2e-3 for a, b in zip(got, exp)):
            bad += 1
            if bad <= 5:
                print('MISMATCH case %d (stages %d): got %s expected %s' % (cases, n, got, exp))
        k += 6
    # fog / dst alpha checked analytically
    c = [0.0] * 1024
    c[3 * 4 + 0], c[3 * 4 + 1], c[3 * 4 + 2] = 2.0, -0.5, 1.0          # f = depth*2 - 0.5
    c[4 * 4 + 0], c[4 * 4 + 1], c[4 * 4 + 2] = 1.0, 0.0, 0.0            # fog colour red
    c[5 * 4 + 0], c[5 * 4 + 1] = 1.0, 0.25                              # dst alpha 0.25
    base = STAGE_BASE
    # stage: d = ras (one-hot weight on candidate ras for input d)
    c[(base + 3 * N_CAND + 6) * 4 + 0] = 1.0
    c[(base + 3 * N_CAND + 6) * 4 + 2] = 1.0
    for lo, hi in ((PAD_CLAMP_LO_C, PAD_CLAMP_HI_C), (PAD_CLAMP_LO_A, PAD_CLAMP_HI_A)):
        c[(base + lo) * 4 + 3] = 0.0
        c[(base + hi) * 4 + 3] = 1.0
    c[(base + PAD_OUT_C0 + 0) * 4 + 3] = 1.0
    c[(base + PAD_OUT_A0 + 0) * 4 + 3] = 1.0
    got = simulate_ps(1, c, [0.2, 0.4, 0.6, 0.8], [0] * 4, [0] * 4, z=1.5, w=3.0)   # depth 0.5 -> f = 0.5
    exp = [0.2 + 0.5 * (1.0 - 0.2), 0.4 + 0.5 * (0.0 - 0.4), 0.6 + 0.5 * (0.0 - 0.6), 0.25]
    cases += 1
    if any(abs(a - b) > 1e-4 for a, b in zip(got, exp)):
        bad += 1
        print('MISMATCH fog/dstalpha: got %s expected %s' % (got, exp))
    print('shader simulator: %d cases, %d mismatches' % (cases, bad))
    return bad == 0


